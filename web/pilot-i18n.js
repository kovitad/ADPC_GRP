  const listeners = [];

  // Remembered choice, then ?lang=, then Thai: this pilot is for the Thailand Hub.
  const initial = () => {
    const asked = new URL(window.location.href).searchParams.get("lang");
    if (asked === "th" || asked === "en") return asked;
    try {
      const saved = window.localStorage.getItem(KEY);
      if (saved === "th" || saved === "en") return saved;
    } catch (error) { /* storage may be blocked */ }
    return "th";
  };
  let lang = initial();

  const t = (key, vars = {}) => {
    const text = (DICT[lang] && DICT[lang][key]) ?? DICT.en[key] ?? key;
    return text.replace(/\{(\w+)\}/g, (_, name) => (name in vars ? String(vars[name]) : `{${name}}`));
  };

  const locale = () => (lang === "th" ? "th-TH" : "en-GB");

  const applyStatic = () => {
    document.documentElement.lang = lang;
    document.title = t(document.documentElement.dataset.titleKey || "page.title");
    document.querySelectorAll("[data-t]").forEach((node) => { node.textContent = t(node.dataset.t); });
    document.querySelectorAll("[data-t-html]").forEach((node) => { node.innerHTML = t(node.dataset.tHtml); });
    document.querySelectorAll("[data-lang]").forEach((button) => {
      button.setAttribute("aria-pressed", String(button.dataset.lang === lang));
    });
  };

  const set = (next) => {
    if (next !== "th" && next !== "en") return;
    lang = next;
    try { window.localStorage.setItem(KEY, next); } catch (error) { /* not remembered */ }
    applyStatic();
    listeners.forEach((fn) => fn(lang));
  };

  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.addEventListener("click", () => set(button.dataset.lang));
  });
  applyStatic();

  // Another pilot page adds its own keys; both languages share the remembered choice.
  const extend = (more) => {
    ["en", "th"].forEach((code) => { Object.assign(DICT[code], more[code] || {}); });
    applyStatic();
  };

  return {
    t,
    locale,
    set,
    extend,
    lang: () => lang,
    onChange: (fn) => listeners.push(fn),
  };
